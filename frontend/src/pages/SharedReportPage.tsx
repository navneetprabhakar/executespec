import { useEffect, useState } from 'react';
import { useParams } from 'react-router-dom';
import { getSharedReport, type SharedReportData } from '@/lib/api';
import { MarkdownContent } from '@/components/shared/MarkdownContent';
import { Shield, Check, Loader2 } from 'lucide-react';
import { cn } from '@/lib/utils';

const SEVERITY_CONFIG: Record<string, { color: string }> = {
  WOULD_BREAK_BUILD: { color: 'bg-red-500/20 text-red-400 border-red-500/30' },
  WOULD_CAUSE_BUG: { color: 'bg-orange-500/20 text-orange-400 border-orange-500/30' },
  WOULD_FAIL_REVIEW: { color: 'bg-yellow-500/20 text-yellow-400 border-yellow-500/30' },
  WOULD_FAIL_LINT: { color: 'bg-zinc-500/20 text-zinc-400 border-zinc-500/30' },
};

export default function SharedReportPage() {
  const { shareToken } = useParams<{ shareToken: string }>();
  const [report, setReport] = useState<SharedReportData | null>(null);
  const [loading, setLoading] = useState(true);
  const [notFound, setNotFound] = useState(false);

  useEffect(() => {
    if (!shareToken) return;
    getSharedReport(shareToken)
      .then(data => {
        if (!data) setNotFound(true);
        else setReport(data);
      })
      .finally(() => setLoading(false));
  }, [shareToken]);

  if (loading) {
    return (
      <div className="min-h-screen bg-zinc-950 flex items-center justify-center">
        <Loader2 className="h-8 w-8 text-zinc-500 animate-spin" />
      </div>
    );
  }

  if (notFound || !report) {
    return (
      <div className="min-h-screen bg-zinc-950 flex flex-col items-center justify-center text-zinc-400 gap-4">
        <Shield className="h-12 w-12 text-zinc-600" />
        <h1 className="text-xl font-semibold text-zinc-200">Report Not Found</h1>
        <p className="text-sm">This validation report doesn't exist or has been removed.</p>
      </div>
    );
  }

  const issueCount = report.issues?.length ?? 0;

  return (
    <div className="min-h-screen bg-zinc-950 text-zinc-200">
      {/* Header */}
      <header className="border-b border-white/[0.08] bg-white/[0.02]">
        <div className="max-w-3xl mx-auto px-6 py-5 flex items-center gap-3">
          <Shield className="h-6 w-6 text-emerald-400" />
          <div>
            <h1 className="text-lg font-semibold">Validation Report</h1>
            <p className="text-xs text-zinc-500">
              {report.filesGenerated} file{report.filesGenerated !== 1 ? 's' : ''} · {report.languages.join(', ') || 'N/A'} · {
                issueCount > 0
                  ? `${issueCount} issue${issueCount !== 1 ? 's' : ''} caught & fixed`
                  : 'Clean run'
              }
            </p>
          </div>
        </div>
      </header>

      {/* Content */}
      <main className="max-w-3xl mx-auto px-6 py-8 space-y-6">
        {/* Severity badges */}
        {issueCount > 0 && (
          <div className="flex flex-wrap gap-2">
            {report.issues.map((issue, i) => {
              const cfg = SEVERITY_CONFIG[issue.severity] ?? SEVERITY_CONFIG.WOULD_FAIL_REVIEW;
              return (
                <span key={i} className={cn('text-xs px-2 py-0.5 rounded-full border', cfg.color)}>
                  {issue.severity.replace(/WOULD_/g, '').replace(/_/g, ' ').toLowerCase()}
                </span>
              );
            })}
          </div>
        )}

        {/* Markdown report */}
        {report.reportMarkdown && (
          <div className="rounded-lg border border-white/[0.08] bg-white/[0.02] p-6">
            <MarkdownContent content={report.reportMarkdown} />
          </div>
        )}

        {/* Checks passed */}
        {report.checksPassed.length > 0 && (
          <div className="flex flex-wrap gap-3">
            {report.checksPassed.map(check => (
              <span key={check} className="flex items-center gap-1.5 text-sm text-emerald-400/80">
                <Check className="h-4 w-4" />
                {check.replace(/_/g, ' ')}
              </span>
            ))}
          </div>
        )}
      </main>

      {/* Footer */}
      <footer className="border-t border-white/[0.08] mt-16">
        <div className="max-w-3xl mx-auto px-6 py-6 text-center text-xs text-zinc-600">
          Generated by <span className="text-zinc-400 font-medium">ExecuteSpec</span> — Don't prompt. Specify.
        </div>
      </footer>
    </div>
  );
}
