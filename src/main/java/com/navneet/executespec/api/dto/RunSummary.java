package com.navneet.executespec.api.dto;

import java.time.Instant;

public record RunSummary(
    String runId,
    String status,
    String userRequest,
    String currentGate,
    Integer queuePosition,
    String plannerModel,
    String workerModel,
    String reviewerModel,
    Integer totalInputTokens,
    Integer totalOutputTokens,
    Instant startedAt,
    Instant completedAt,
    String repoUrl,
    String repoMode,
    /** Project this run belongs to, or null for un-grouped runs. */
    String projectId,
    /** Billing flag: SYSTEM | OWN_KEYS | HYBRID. Null for pre-migration runs. */
    String keySource,
    /**
     * Comma-separated tech stack IDs derived from the plan (e.g. "react,typescript,nodejs"). Null
     * until planning completes.
     */
    String techStack,
    /** Human-readable project name. Null if projectId is null or project was deleted. */
    String projectName,
    /**
     * Display name of the user who created this run (e.g. "John Doe"). Null for pre-ownership runs.
     */
    String createdByName,
    /** Short 3-8 word title generated by the planner. Null until planning completes. */
    String runTitle,
    /** One-sentence plan summary from the planner. Null until planning completes. */
    String runSummary,
    /** "PROTOTYPE" | "PRODUCTION". Null for pre-V40 runs. */
    String executionMode,
    /** Timestamp when the run was archived by the user. Null for active runs. */
    Instant archivedAt,
    /** "REALTIME" | "BATCH". Null for pre-V61 runs or runs not yet approved. */
    String approvedExecutionMode,
    /** AI provider used for this run (ANTHROPIC, OPENAI, GOOGLE). */
    String aiProvider,
    /** True if this run is a retry of a previous run. */
    Boolean isRetry,
    /** RunId of the original run this was retried from. Null for original runs. */
    String sourceRunId,
    /** Which harness produced this run: "v1" (default) or "v2". */
    String harnessVersion,
    /** v2.5.8 — total USD spent on LLM calls for this run. Null before terminal. */
    Double actualCostUsd,
    /**
     * v2.5.10 — explicit reason for the terminal status (CLEAN_COMPLETION,
     * CLEAN_WITH_INTERMEDIATE_WARNINGS, FINAL_BUILD_FAILED, TESTS_FAILED:N_OF_M,
     * REVIEWER_UNRESOLVED, REVIEWER_FAILED, ALL_TASKS_FAILED, LEGACY_UNKNOWN). Null on in-flight
     * runs and on pre-v2.5.10 terminal runs that were never backfilled. Populated by
     * RunOrchestrator when scoring.v2-verified is on.
     */
    String statusReason) {}
