package com.navneet.executespec.api.dto;

import java.time.Instant;
import java.util.List;

import com.fasterxml.jackson.databind.JsonNode;
import com.navneet.executespec.run.outcome.RunTerminalOutcome;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * Full detail DTO for a single pipeline run, including task list and review data.
 *
 * <p>Converted from a record to a {@code @Builder} class to support Tier 8's optional {@code
 * hasFrontend}, {@code hasApiSpec}, and {@code previewStatus} fields without requiring every
 * constructor callsite to pass them.
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class RunDetail {

  String runId;
  String status;
  String userRequest;
  String currentGate;
  Integer queuePosition;
  String plannerModel;
  String workerModel;
  String reviewerModel;
  Integer totalInputTokens;
  Integer totalOutputTokens;
  Instant startedAt;
  Instant completedAt;
  String repoUrl;
  String repoMode;
  String failureReason;

  /** v2.5.10 — explicit terminal-status reason. See RunSummary.statusReason. */
  String statusReason;

  /** Server-owned customer-safe interpretation of terminal status/failure evidence. */
  RunTerminalOutcome terminalOutcome;

  String planJson;
  String reviewJson;

  /** Durable final run-level goal proof derived from the validation-report ledger. */
  JsonNode runGoalDoneness;

  List<TaskSummary> tasks;
  IntegrationSource integrationSource; // null for manual runs

  // Tier 8: Compile, API spec, preview
  Boolean hasFrontend; // true once PreviewService builds the frontend
  Boolean hasApiSpec; // true once ApiTestSuiteAgent writes openapi.yaml
  String previewStatus; // null | "READY" | "FAILED"

  /** Billing flag: SYSTEM | OWN_KEYS | HYBRID. Null for pre-migration runs. */
  String keySource;

  /** Pre-run cost estimate range (USD). Set at plan creation, shown at approval gate. */
  Double costEstimateLow;

  Double costEstimateHigh;

  /** Actual cost in USD computed after run completion. Null until complete. */
  Double actualCostUsd;

  /** Run credits charged (proportional to estimated cost). */
  Integer creditsCharged;

  /**
   * Additive refund marker backed by the durable V300 {@code run_quota_refund} compensation ledger.
   * {@code true} when a durable refund row exists for this run (PENDING rows are idempotently
   * applied, so the durable intent is refund evidence); {@code false} when the run is terminal
   * non-success (FAILED/ERROR/PARTIAL/CANCELLED/ABORTED/REJECTED display status) with no refund
   * row; {@code null} when not applicable (non-terminal or success) or when refund state could not
   * be resolved.
   */
  Boolean creditsRefunded;

  /** Managed AI credits actually debited by successful platform-key model calls for this run. */
  Long aiCreditsCharged;

  /** Customer-selected voluntary ceiling, even when planning failed before deriving a hard cap. */
  Double userCostCapUsd;

  /** Hard cap in USD (safety ceiling). */
  Double hardCapUsd;

  /**
   * v2.6.2-track — hierarchical-planner strategy chosen by SmartClassifierAgent. SINGLE_SHOT |
   * SMALL | MEDIUM | LARGE | LEGACY. Null for runs that submitted before slice 1 of the rollout.
   */
  String planStrategy;

  /** v2.6.2-track — one-line classifier rationale (heuristic vs LLM verdict). */
  String classifierReasoning;

  /** v2.6.2-track — phase 0 cost (USD). Null when phase didn't run. */
  Double classifierCostUsd;

  Long classifierInputTokens;
  Long classifierOutputTokens;

  /** v2.6.2-track — phase 1 cost. */
  Double outlineCostUsd;

  Long outlineInputTokens;
  Long outlineOutputTokens;

  /** v2.6.2-track — phase 2 cost (sum across parallel expansion calls). */
  Double expansionCostUsd;

  Long expansionInputTokens;
  Long expansionOutputTokens;

  /** v2.6.2-track — phase 3 cost. */
  Double coherenceCostUsd;

  Long coherenceInputTokens;
  Long coherenceOutputTokens;

  /** Comma-separated tech stack IDs derived from the plan (e.g. "react,typescript,nodejs"). */
  String techStack;

  /**
   * Project this run belongs to (UUID). Drives "Open run" navigation in V3ProjectHome — without
   * this field the frontend can't construct {@code /projects/{projectId}/runs/{runId}} and falls
   * back to {@code /runs/{runId}}, which the v2 dispatcher then redirects to the user's default
   * project home (i.e. wrong project entirely). Added 2026-05-02 after pinning that exact misroute
   * to a missing wire field.
   */
  String projectId;

  /** Human-readable project name. Null if projectId is null or project was deleted. */
  String projectName;

  /**
   * Display name of the user who created this run (e.g. "John Doe"). Null for pre-ownership runs.
   */
  String createdByName;

  /** Number of apply-suggestion actions used on this run (chat copilot + review combined). */
  Integer applySuggestionCount;

  /** Short 3-8 word title generated by the planner. Null until planning completes. */
  String runTitle;

  /** One-sentence plan summary from the planner. Null until planning completes. */
  String runSummary;

  /** "PROTOTYPE" | "PRODUCTION". Null for pre-V40 runs. */
  String executionMode;

  /** URL of the pull request created for existing-repo runs. Null for NEW/NONE repos. */
  String githubPrUrl;

  /** Canonical PR URL — works for GitHub and Bitbucket. Null for NEW/NONE repos or legacy runs. */
  String scmPrUrl;

  /** Which SCM provider was used for this run (GITHUB, BITBUCKET, or null for legacy runs). */
  String scmProvider;

  /** Pilot R4 — JSON {@code AssessmentResult}. Null when no project context. */
  String assessmentResult;

  /** Pilot R7 — Figma URL captured at submission. */
  String figmaUrl;

  /** Codemap stats for paid existing-repo runs (null when not generated). */
  Integer codemapFileCount;

  Integer codemapRouteCount;
  Integer codemapInputTokens;
  Integer codemapOutputTokens;

  /** Timestamp when the run was archived by the user. Null for active runs. */
  Instant archivedAt;

  /** AI provider used for this run (ANTHROPIC, OPENAI, GOOGLE). */
  String aiProvider;

  /** Caller-selected provider preserved independently from the effective dispatch route. */
  String requestedProvider;

  /** Caller-selected exact model, or null when provider-tier routing was requested. */
  String requestedModel;

  /** AUTO, PROVIDER_PREFERRED, or EXACT_LOCK. */
  String routingMode;

  /** True when every run-scoped LLM dispatch must use requestedProvider/requestedModel. */
  Boolean routePinned;

  /**
   * C1 (2026-07-19) — DERIVED, not a column. The physical provider that actually served this run,
   * projected from the {@code run_step_usage} attempt ledger. Null when the run was served by more
   * than one route ({@code effectiveRouteAttribution=MIXED}) or by none yet ({@code UNATTRIBUTED});
   * a mixed-route run is deliberately not collapsed to one of its providers.
   */
  String effectiveProvider;

  /** C1 — DERIVED physical model that actually served this run. Null when MIXED/UNATTRIBUTED. */
  String effectiveModel;

  /** C1 — {@code LEDGER} | {@code MIXED} | {@code UNATTRIBUTED}. */
  String effectiveRouteAttribution;

  /**
   * C1 — true when the ledger proves the served route is not the requested one (failover,
   * managed-AI tier lock or model step-down), or when the run was served by multiple routes. Blank
   * requested fields are treated as "not requested", so an AUTO-routed run is not reported as
   * diverged merely for having no pinned model.
   */
  Boolean routeDiverged;

  /** Which harness produced this run: "v1" (default) or "v2". Null for pre-V76 rows. */
  String harnessVersion;

  /**
   * V183 (2026-05-08) — pipeline shape: {@code BUILD} (default; planner + executor + reviewer) or
   * {@code PATCH} (single thin-agent loop, used by SWE-bench / autofix runs). The frontend renders
   * different evidence chips per mode so PATCH runs aren't judged against build-mode signals (build
   * pass / reviewer verdict / endpoint coverage) that don't apply.
   */
  String runMode;

  /** Exact durable BUILD frontier; null for PATCH and legacy pre-V374 runs. */
  String acceptedWorkspaceGeneration;

  /** Zero-based task index represented by the accepted frontier (-1 is the post-clone baseline). */
  Integer acceptedTaskIndex;

  /** Immutable generation-attempt receipt that advanced the frontier. */
  String acceptedGenerationAttemptId;

  /** Storage class of the accepted internal generation checkpoint; never the customer ZIP key. */
  String acceptedCheckpointKind;

  /** SHA-256 of the exact accepted internal checkpoint bytes. */
  String acceptedCheckpointDigest;

  /** Completion time of the exact checkpoint copied into the accepted frontier receipt. */
  java.time.Instant acceptedCheckpointCompletedAt;

  /**
   * Bounded newest-first BUILD generation history. Failure reasons and rejected patches stay
   * server-side; clients receive immutable digests and stable failure codes only.
   */
  List<WorkspaceGenerationAttemptEvidence> workspaceGenerationAttempts;

  /**
   * V183 — finding source key for autofix-triggered patch runs. {@code <TYPE>:<id>}. Null
   * otherwise.
   */
  String triggeredByFinding;

  /** True if this run is a retry of a previous run. */
  Boolean isRetry;

  /** RunId of the original run this was retried from. Null for original runs. */
  String sourceRunId;

  /** Number of auto-retry attempts on this run chain (0 = original run). */
  Integer runRetryCount;

  /** "REALTIME" or "BATCH". Null for pre-V61 runs. */
  String approvedExecutionMode;

  /** Batch credits (with 50% discount). Null if batch not available. */
  Integer batchCredits;

  /** True if this run qualifies for batch execution. */
  Boolean batchAvailable;

  /** Credits saved by choosing batch over real-time. */
  Integer creditSavings;

  /** Batch progress: tasks completed so far. */
  Integer batchProgressCompleted;

  /** Batch progress: total tasks in batch. */
  Integer batchProgressTotal;

  // Per-agent token breakdown (V19)
  /** Token usage + actual provider/model for pipeline agents (planner, reviewer, compiler). */
  List<AgentTokenEntry> agentTokens;

  // Background validation (V64)
  /** Status of the background validation thread: PENDING, RUNNING, COMPLETED, FAILED, or null. */
  String validationStatus;

  /** Current phase of background validation (TEST_GEN, REVIEW, RE_VALIDATE, REPORT). */
  String validationPhase;

  // Validation report scoring snapshot (v2.5.10 + adversarial-report Finding 13)
  /**
   * Mirrors the corresponding fields on the {@code ValidationReport} so clients rendering run
   * detail don't have to issue a second request to {@code GET /api/runs/{id}/report} just to show
   * the headline score. Null until the report is written.
   */
  Integer verifiedScore;

  Integer accuracyScore;
  String reviewerVerdict;

  /** Physical reviewer provider persisted from the reviewer call attribution. */
  String reviewerProvider;

  /** Physical reviewer model persisted from the reviewer call attribution. */
  String reviewerEffectiveModel;

  Boolean finalBuildPassed;
  Integer testsPassed;
  Integer testsTotal;
  Integer testsSkipped;

  /** True only when the test totals came from an actual executed command. */
  Boolean testExecutionVerified;

  /** Durable validation lifecycle state; null when no report exists. */
  String validationEvidenceStatus;

  /** Exact workspace generation to which the validation report is bound. */
  String evidenceWorkspaceGeneration;

  /** Deterministic workflow/config parser result: PASS/FAILED/NOT_APPLICABLE/UNAVAILABLE. */
  String workflowConfigStatus;

  /** Human-readable deterministic workflow/config evidence summary. */
  String workflowConfigReason;

  /** Immutable admitted brownfield HTTP baseline digest, when this is an existing-code run. */
  String brownfieldHttpBaselineDigest;

  /** Most recently measured workspace HTTP surface digest. */
  String brownfieldHttpCurrentDigest;

  /** BASELINE/COMPATIBLE/BREAKING, or null when the gate does not apply. */
  String brownfieldHttpCompatibilityStatus;

  /** Present if this run was triggered by an external integration. */
  public record IntegrationSource(String sourceType, String sourceId, String sourceUrl) {}

  /** Customer-safe durable evidence for one accepted, rejected, or unresolved BUILD generation. */
  public record WorkspaceGenerationAttemptEvidence(
      String attemptId,
      String taskId,
      Integer taskIndex,
      Integer attemptNumber,
      String attemptKind,
      String state,
      String priorAcceptedGeneration,
      String beforeGeneration,
      String candidateGeneration,
      String acceptedGeneration,
      String taskContractDigest,
      WorkspaceGenerationInitialFailureEvidence initialFailureEvidence,
      String runtimeSurface,
      String baselineKind,
      String buildCommand,
      String testCommand,
      List<String> requiredPaths,
      List<WorkspaceGenerationAcceptanceCheck> acceptanceChecks,
      String requestedProvider,
      String requestedModel,
      String effectiveProvider,
      String effectiveModel,
      Integer workerIterations,
      Integer workerToolCalls,
      Long modelCalls,
      Long inputTokens,
      Long outputTokens,
      Long cacheReadTokens,
      Long cacheWriteTokens,
      Long reasoningTokens,
      java.math.BigDecimal costUsd,
      String verificationReceiptId,
      String verificationOutcome,
      Boolean verificationBuildPassed,
      Boolean verificationTestsExecuted,
      Integer verificationTestsPassed,
      Integer verificationTestsFailed,
      String verificationFailureCategory,
      String verificationEnvironmentCode,
      String verificationExecutionBoundary,
      com.navneet.executespec.workspacegeneration.WorkspaceGenerationFailureProjection
          failureProjection,
      String verificationEvidenceDigest,
      String rejectedDiffDigest,
      String failureCode,
      String recoveryFailureCode,
      Instant recoveryFailureAt,
      Integer recoveryAttemptCount,
      Instant recoveryNextAttemptAt,
      String recoverySupportId,
      Instant recoveryExhaustedAt,
      String recoveryStatus,
      Boolean recoveryUserActionRequired,
      Instant createdAt,
      Instant resolvedAt) {}

  public record WorkspaceGenerationInitialFailureEvidence(
      String outcome,
      String code,
      String detail,
      String command,
      List<String> failedTargets,
      Instant observedAt) {}

  public record WorkspaceGenerationAcceptanceCheck(
      String kind, String target, boolean hidden, String outcome, String detail) {}

  /** Token usage for a non-task agent (planner, reviewer, compiler). */
  public record AgentTokenEntry(
      String role, String provider, String model, int inputTokens, int outputTokens) {}
}
